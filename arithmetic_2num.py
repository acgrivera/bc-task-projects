print("Please give 2 numbers")
First_Num = int(input("First Number: "))
Second_Num = int(input("Second Number: "))

print(f"The sum of your numbers is: {First_Num+Second_Num}.") #Sum of 2 numbers (Addition)
print(f"The difference of your numbers (First - Second) is: {First_Num-Second_Num}.") #Difference of 2 numbers (Subtraction)
print(f"The product of your numbers is: {First_Num*Second_Num}.\n") #Product of 2 numbers (Multiplication)